// Conexão com o banco.
//
// UNIDADE 3: PostgreSQL 16 (pacote `pg`), alcançado por DATABASE_URL (ADR 0001 → ADR 0002).
// O contrato com o resto do código não mudou: `query()` devolve `{ rows }` (e `alteradas`
// nas escritas sem RETURNING). Este continua sendo o único arquivo que conhece o banco.
import pg from 'pg';

const { Pool } = pg;

// O único banco que pode ser apagado: o banco de teste, com nome próprio (vitest.config.js).
// No PostgreSQL não existe ':memory:' — desenvolvimento e teste ficam no mesmo servidor,
// então a trava confere o NOME do banco conectado (ADR 0002 → `## Revisão — 20/10/2026`).
export const BANCO_DE_TESTE = 'pratocheio_teste';

const URL_PADRAO = 'postgres://pratocheio:pratocheio@localhost:5432/pratocheio';

let pool;

// Lido na hora de abrir a conexão (e não no carregamento do módulo), para que o banco em
// uso seja sempre o da conexão aberta — é ele que limparBanco() confere.
function urlConfigurada() {
  return process.env.DATABASE_URL || URL_PADRAO;
}

export function conexao() {
  if (!pool) {
    pool = new Pool({ connectionString: urlConfigurada() });
  }
  return pool;
}

/** Nome do banco da conexão em uso, perguntado ao próprio servidor. */
export async function bancoEmUso() {
  const { rows } = await conexao().query('SELECT current_database() AS nome');
  return rows[0].nome;
}

// Aceita os dois marcadores: `$1, $2…` (dialeto do PostgreSQL, usado no repositorio.js) e
// `?` (o da Unidade 1, ainda usado na preparação de alguns testes). Se o SQL já tem `$n`,
// passa direto; senão, cada `?` vira o próximo `$n`.
function paraMarcadoresDoPostgres(sql) {
  if (/\$\d/.test(sql)) return sql;
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
}

/**
 * Executa uma consulta e devolve { rows }.
 * Use `$1, $2…` como marcador de parâmetro (evita injeção de SQL):
 *   query('SELECT * FROM doacoes WHERE id = $1', [id])
 */
export async function query(sql, valores = []) {
  const resultado = await conexao().query(paraMarcadoresDoPostgres(sql), valores);
  return { rows: resultado.rows, alteradas: resultado.rowCount };
}

/** Cria o schema, se ainda não existir. Rodado por `npm run db:migrar` e ao subir o servidor. */
export async function migrar() {
  // `criada_em` continua TEXTO no formato 'AAAA-MM-DD HH:MM:SS' (UTC), igual ao do SQLite:
  // é o formato que as regras (src/doacoes.js) leem. Com TIMESTAMP o `pg` devolveria um
  // objeto Date e a troca de banco vazaria para as regras de negócio.
  await conexao().query(`
    CREATE TABLE IF NOT EXISTS doacoes (
      id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tipo        TEXT NOT NULL,
      quantidade  TEXT NOT NULL,
      validade    TEXT NOT NULL,
      status      TEXT NOT NULL DEFAULT 'disponivel',
      ong         TEXT,
      criada_em   TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
      coletada_em TEXT
    )
  `);
  // Bancos criados antes da história "voluntário marca a doação como coletada" não têm a
  // coluna: ela é acrescentada sem apagar nada.
  await conexao().query('ALTER TABLE doacoes ADD COLUMN IF NOT EXISTS coletada_em TEXT');
}

/**
 * Apaga todos os dados. Usado pelos testes — e SÓ funciona no banco de teste.
 *
 * Mudança de contexto (Trabalho 2, etapa 4): os testes rodaram na máquina do piloto com a
 * configuração apontando para o banco real, e esta limpeza apagou todas as doações. Agora
 * ela pergunta ao servidor qual banco está conectado e recusa qualquer um que não seja o de
 * teste, seja qual for a máquina, a variável de ambiente ou o arquivo de configuração.
 */
export async function limparBanco() {
  const banco = await bancoEmUso();
  if (banco !== BANCO_DE_TESTE) {
    throw new Error(
      `limpeza recusada: o banco em uso é "${banco}", não o banco de teste ` +
      `("${BANCO_DE_TESTE}"). Nenhuma doação foi apagada.`
    );
  }
  await conexao().query('DELETE FROM doacoes');
}

export async function encerrar() {
  if (pool) {
    const aberto = pool;
    pool = undefined;
    await aberto.end();
  }
}
